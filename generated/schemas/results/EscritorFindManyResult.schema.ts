import * as z from "zod";
export const EscritorFindManyResultSchema = z.object({
	data: z.array(
		z.object({
			id: z.number().int(),
			nombres: z.string().optional(),
			apellidos: z.string().optional(),
			alias: z.string().optional(),
			descripcion: z.string().optional(),
			fechaNacimiento: z.date().optional(),
			createdAt: z.date(),
			updatedAt: z.date(),
			usuarioId: z.number().int().optional(),
			usuario: z.unknown().optional(),
			avatarId: z.number().int(),
			avatar: z.unknown(),
			estadoId: z.number().int(),
			estado: z.unknown(),
			libros: z.array(z.unknown()),
			comentarios: z.array(z.unknown()),
			favoritos: z.array(z.unknown()),
			glosarios: z.array(z.unknown()),
			notasAutor: z.array(z.unknown()),
			marcadores: z.array(z.unknown()),
			seguidores: z.array(z.unknown()),
			siguiendo: z.array(z.unknown()),
		}),
	),
	pagination: z.object({
		page: z.number().int().min(1),
		pageSize: z.number().int().min(1),
		total: z.number().int().min(0),
		totalPages: z.number().int().min(0),
		hasNext: z.boolean(),
		hasPrev: z.boolean(),
	}),
});
