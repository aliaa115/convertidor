import * as z from "zod";
export const LibroFindManyResultSchema = z.object({
	data: z.array(
		z.object({
			id: z.number().int(),
			titulo: z.string(),
			resumen: z.string(),
			portada: z.string().optional(),
			publicado: z.boolean(),
			fechaPublicacion: z.date().optional(),
			createdAt: z.date(),
			updatedAt: z.date(),
			escritorId: z.number().int(),
			escritor: z.unknown(),
			tipoId: z.number().int(),
			tipo: z.unknown(),
			estadoId: z.number().int(),
			estado: z.unknown(),
			idiomaId: z.number().int(),
			idioma: z.unknown(),
			capitulos: z.array(z.unknown()),
			categorias: z.array(z.unknown()),
			etiquetas: z.array(z.unknown()),
			favoritos: z.array(z.unknown()),
			glosarios: z.array(z.unknown()),
			listaLibros: z.array(z.unknown()),
		}),
	),
	pagination: z.object({
		page: z.number().int().min(1),
		pageSize: z.number().int().min(1),
		total: z.number().int().min(0),
		totalPages: z.number().int().min(0),
		hasNext: z.boolean(),
		hasPrev: z.boolean(),
	}),
});
